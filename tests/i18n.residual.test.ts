describe('i18n-Restgruppen: en ist nicht de', () => {
  test('kein Schluessel der Restgruppen ist in beiden Sprachen identisch', () => {
    const gleich = GRUPPE.filter(
      k => !ABSOLUTE.has(k) && de[k as keyof typeof de] === en[k as keyof typeof en]
    ).sort();
    expect(gleich).toEqual([]);
  });

  test('die Restgruppen-Schluessel stehen in beiden Wörterbüchern', () => {
    const fehlt = GRUPPE.filter(k => !(k in de) || !(k in en));
    expect(fehlt).toEqual([]);
  });
});
